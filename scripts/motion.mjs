import { chromium } from '@playwright/test';
import { mkdir, writeFile, copyFile } from 'node:fs/promises';
const out = 'artifacts/captures/release-4';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1024, height: 768 }, deviceScaleFactor: 1, recordVideo: { dir: out, size: { width: 1024, height: 768 } } });
const page = await context.newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message));
const samples = [];
await page.goto('http://127.0.0.1:4318/?qa=1');
await page.getByRole('heading', { name: '窃符', exact: true }).waitFor();
await page.getByRole('button', { name: /取符之夜.*潜行/ }).click();
await page.getByRole('heading', { name: '取符之夜', exact: true }).waitFor();
await page.keyboard.down('d');
await page.waitForFunction(() => window.__DIGITAL_WORLD__.getNight().x >= -3.2);
await page.keyboard.up('d');
samples.push(await page.evaluate(() => ({ view: window.__DIGITAL_WORLD__.getNight(), render: window.__DIGITAL_WORLD__.getDiagnostics() })));
await page.screenshot({ path: `${out}/motion-moving.png` });
await page.getByRole('button', { name: '暂停', exact: true }).click();
await page.screenshot({ path: `${out}/motion-paused.png` });
await page.getByRole('button', { name: /继续这场戏/ }).click();
await page.keyboard.down('a');
await page.waitForFunction(() => window.__DIGITAL_WORLD__.getNight().x <= -4.9);
await page.keyboard.up('a');
samples.push(await page.evaluate(() => ({ view: window.__DIGITAL_WORLD__.getNight(), render: window.__DIGITAL_WORLD__.getDiagnostics() })));
await page.screenshot({ path: `${out}/motion-returned.png` });
const video = page.video();
await context.close();
await copyFile(await video.path(), `${out}/night-motion.webm`);
await browser.close();
await writeFile(`${out}/motion.json`, JSON.stringify({ runId: 'release-20261011-4', input: 'Arrow/WASD right, pause, resume, left', samples, errors }, null, 2));
console.log(JSON.stringify({ samples: samples.map(s => ({ x: s.view.x, z: s.view.z, render: s.render })), errors }));
